class CameraState:
    def __init__(self):
        self.lock = threading.Lock()
        self.frame = None
        self.updated = 0.0
        self.count = 0

class CameraProcessor:
    def __init__(self):
        self.state = st.session_state.camera_state
    def recv(self, frame):
        image = frame.to_ndarray(format="bgr24")
        with self.state.lock:
            self.state.frame = image.copy()
            self.state.updated = time.monotonic()
            self.state.count += 1
        return av.VideoFrame.from_ndarray(image, format="bgr24")

if "camera_state" not in st.session_state:
    st.session_state.camera_state = CameraState()
if "analysis_text" not in st.session_state:
    st.session_state.analysis_text = "Camera analysis has not run yet."
if "analysis_time" not in st.session_state:
    st.session_state.analysis_time = "Waiting for first analysis"
