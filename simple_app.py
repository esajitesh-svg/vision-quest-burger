    ask_text = st.button("SEND QUESTION", use_container_width=True)
    ask_audio = False
    if audio is not None:
        audio_hash = hashlib.sha256(audio.getvalue()).hexdigest()
        ask_audio = audio_hash != st.session_state.last_audio_hash
